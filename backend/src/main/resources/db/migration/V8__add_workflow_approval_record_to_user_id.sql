-- ----------------------------------------------------------------------------
-- 审批引擎：审批轨迹表补充"新处理人"字段
-- ----------------------------------------------------------------------------
-- V7 的 tab_wf_approval_record 只设计了 from_user_id（转办/委派场景的原处理人），
-- 转办/委派的目标处理人此前只能拼进 remark 文本，无法结构化查询"谁把任务转给了我"。
-- 本脚本补一个 to_user_id 列承载目标处理人，其余动作类型该列为空。

ALTER TABLE `tab_wf_approval_record`
    ADD COLUMN `to_user_id` BIGINT NULL COMMENT '转办/委派场景记录的新处理人用户 id，其余场景为空'
        AFTER `from_user_id`;
